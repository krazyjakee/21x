import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { act, cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { DEFAULT_ROLLOVER_POLICY, type SessionContextSnapshot } from '@shared/session-context'
const mocks = vi.hoisted(() => ({ getSnapshot: vi.fn(), setPolicy: vi.fn(), cancel: vi.fn(), stopByTaskId: vi.fn() }))
vi.mock('@/lib/ipc-client', () => ({ sessionContextApi: mocks, commanderApi: { onEvent: () => () => {}, cancel: mocks.cancel }, agentSessionApi: { stopByTaskId: mocks.stopByTaskId }, onAgentStatus: () => () => {}, onTranscriptChanged: () => () => {} }))
import { SessionContextMeter, contextReading } from './SessionContextMeter'

function snapshot(usage: Partial<SessionContextSnapshot['usage']> = {}): SessionContextSnapshot {
  return { scope: { kind: 'commander', ownerId: 's1' }, generation: { id: 'internal-id', key: 'generation-key', engine: 'chat', state: 'idle', backendId: null, createdAt: 1 }, usage: { tokens: 4000, source: 'reported', contextWindow: 10000, model: 'model', observedAt: 10, ...usage }, counters: { compactions: 2, wakeups: 150, turns: 300, ageMs: 7 * 86400000 }, policy: { ...DEFAULT_ROLLOVER_POLICY }, reasons: [], warnings: [], summaries: [] }
}
beforeEach(() => { vi.clearAllMocks(); mocks.getSnapshot.mockResolvedValue(snapshot()); mocks.setPolicy.mockImplementation(async policy => policy); vi.spyOn(document, 'hidden', 'get').mockReturnValue(false) })
afterEach(() => { cleanup(); vi.restoreAllMocks() })

describe('current-generation context meter', () => {
  it('distinguishes reported and estimated readings and never infers unknown tokens/capacity', () => {
    expect(contextReading(snapshot().usage)).toMatchObject({ value: '40%', description: 'Reported context: 4,000 tokens of 10,000 (40%)' })
    expect(contextReading(snapshot({ source: 'estimated' }).usage)).toMatchObject({ value: '≈40%', description: 'Estimated context: ≈4,000 tokens of 10,000 (≈40%)' })
    expect(contextReading(snapshot({ source: 'unknown', tokens: 999999 }).usage)).toMatchObject({ tokens: null, value: 'unknown' })
    expect(contextReading(snapshot({ contextWindow: null }).usage)).toMatchObject({ percent: null, value: '4,000 tokens' })
    expect(contextReading(snapshot({ tokens: 0 }).usage)).toMatchObject({ value: '0%' })
    expect(contextReading(snapshot({ tokens: Infinity }).usage)).toMatchObject({ value: 'unknown' })
  })
  it('shows estimated usage, expandable fallback summaries and warnings without exposing generation identifiers on the trigger', async () => {
    mocks.getSnapshot.mockResolvedValue({ ...snapshot({ source: 'estimated' }), reasons: ['context'], warnings: ['A durable handoff is pending.'], summaries: [{ id: 'summary', kind: 'rollover', content: 'Preserved **checkout decisions** and remaining work.', source: 'fallback', createdAt: 1 }] })
    render(<SessionContextMeter scope={{ kind: 'commander', ownerId: 's1' }} />)
    const trigger = await screen.findByRole('button', { name: 'Commander context: ≈40%, warnings available' })
    expect(trigger).not.toHaveTextContent('generation-key')
    fireEvent.click(trigger)
    const dialog = screen.getByRole('dialog', { name: 'Commander context' })
    expect(within(dialog).getByRole('meter')).toHaveAttribute('aria-valuetext', 'Estimated context: ≈4,000 tokens of 10,000 (≈40%)')
    expect(within(dialog).getByText('Context threshold reached')).toBeTruthy()
    expect(within(dialog).getByText('A durable handoff is pending.')).toBeTruthy()
    expect(within(dialog).getByText('Fallback summary')).toBeTruthy()
    const disclosure = within(dialog).getByText('Read handoff summary')
    expect(disclosure.closest('details')).not.toHaveAttribute('open')
    fireEvent.click(disclosure); expect(disclosure.closest('details')).toHaveAttribute('open')
    expect(within(dialog).getByText('checkout decisions').tagName).toBe('STRONG')
  })
  it('preserves unknown capacity and source failures without a misleading zero meter', async () => {
    mocks.getSnapshot.mockResolvedValue(snapshot({ contextWindow: null }))
    const view = render(<SessionContextMeter scope={{ kind: 'commander', ownerId: 's1' }} />)
    fireEvent.click(await screen.findByRole('button', { name: 'Commander context: 4,000 tokens' }))
    expect(screen.queryByRole('meter')).toBeNull()
    expect(screen.getByText(/no percentage is inferred/)).toBeTruthy()
    view.unmount()
    mocks.getSnapshot.mockRejectedValue(new Error('Backend unavailable'))
    render(<SessionContextMeter scope={{ kind: 'commander', ownerId: 's1' }} />)
    fireEvent.click(await screen.findByRole('button', { name: 'Commander context: unavailable' }))
    expect(screen.getByTestId('context-usage-description')).toHaveTextContent('Context usage unknown')
    expect(screen.queryByRole('meter')).toBeNull()
  })
  it('exposes shared defaults and saves managed policy directly, without making a conversation turn', async () => {
    render(<SessionContextMeter scope={{ kind: 'commander', ownerId: 's1' }} />)
    fireEvent.click(await screen.findByRole('button', { name: 'Commander context: 40%' }))
    const settings = screen.getByText('Conversation continuation settings'); fireEvent.click(settings)
    expect(settings.closest('details')).toHaveAttribute('open')
    expect(screen.getByLabelText('Conversation continuation')).toHaveValue('off')
    expect(screen.getByLabelText('Context threshold (%)')).toHaveValue(70)
    expect(screen.getByLabelText('Compactions')).toHaveValue(2)
    expect(screen.getByLabelText('Wakeups')).toHaveValue(150)
    expect(screen.getByLabelText('Turns')).toHaveValue(300)
    expect(screen.getByLabelText('Maximum context age (days)')).toHaveValue(7)
    fireEvent.change(screen.getByLabelText('Conversation continuation'), { target: { value: 'observe' } })
    fireEvent.change(screen.getByLabelText('Context threshold (%)'), { target: { value: '65.5' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save settings' }))
    await waitFor(() => expect(mocks.setPolicy).toHaveBeenCalledWith({ ...DEFAULT_ROLLOVER_POLICY, mode: 'observe', contextRatio: .655 }))
    expect(await screen.findByText('Conversation continuation settings saved.')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Restore defaults' }))
    expect(screen.getByLabelText('Conversation continuation')).toHaveValue('off')
    expect(mocks.setPolicy).toHaveBeenCalledOnce()
    mocks.setPolicy.mockRejectedValue(new Error('Write rejected'))
    fireEvent.click(screen.getByRole('button', { name: 'Save settings' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('The settings could not be saved')
  })
  it('keeps keyboard focus inside the context dialog and restores its trigger on close', async () => {
    render(<SessionContextMeter scope={{ kind: 'commander', ownerId: 's1' }} />)
    const trigger = await screen.findByRole('button', { name: 'Commander context: 40%' }); trigger.focus(); fireEvent.click(trigger)
    await waitFor(() => expect(screen.getByRole('dialog', { name: 'Commander context' })).toContainElement(document.activeElement as HTMLElement))
    fireEvent.keyDown(document.activeElement!, { key: 'Escape' })
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    await waitFor(() => expect(trigger).toHaveFocus())
    expect(mocks.setPolicy).not.toHaveBeenCalled()
  })
  it('offers a keyboard Stop for idle Commander continuation, coalesces presses and reloads after cancellation', async () => {
    let resolve!: (result: { cancelled: boolean }) => void
    const stopped = new Promise<{ cancelled: boolean }>(yes => { resolve = yes })
    mocks.cancel.mockReturnValue(stopped)
    const pending = { ...snapshot(), generation: { ...snapshot().generation!, state: 'open' }, handoff: { id: 'handoff', state: 'summarizing' } }
    mocks.getSnapshot.mockResolvedValue(pending)
    render(<SessionContextMeter scope={{ kind: 'commander', ownerId: 's1' }} />)
    fireEvent.click(await screen.findByRole('button', { name: 'Commander context: 40%, warnings available' }))
    expect(screen.getByText('Current generation · Open')).toBeTruthy()
    const stop = screen.getByRole('button', { name: 'Stop context continuation' }); stop.focus()
    expect(stop).toHaveFocus(); expect(stop.tagName).toBe('BUTTON')
    fireEvent.click(stop)
    expect(screen.getByRole('button', { name: 'Stopping…' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: 'Stopping…' }))
    expect(mocks.cancel).toHaveBeenCalledOnce(); expect(mocks.cancel).toHaveBeenCalledWith('s1')
    expect(mocks.stopByTaskId).not.toHaveBeenCalled()
    mocks.getSnapshot.mockResolvedValue({ ...snapshot(), handoff: null })
    await act(async () => { resolve({ cancelled: true }); await stopped })
    await waitFor(() => expect(screen.queryByRole('button', { name: 'Stop context continuation' })).toBeNull())
    expect(mocks.getSnapshot).toHaveBeenCalledTimes(2)
  })
  it('stops Captain continuation through its task identity and keeps failure feedback visible after refresh', async () => {
    mocks.getSnapshot.mockResolvedValue({ ...snapshot(), scope: { kind: 'captain', ownerId: 'captain-row' }, generation: { ...snapshot().generation!, state: 'interrupted' }, handoff: { id: 'captain-handoff', state: 'prepared' } })
    mocks.stopByTaskId.mockRejectedValue(new Error('Stop failed'))
    render(<SessionContextMeter scope={{ kind: 'captain', ownerId: 'captain-row' }} />)
    fireEvent.click(await screen.findByRole('button', { name: 'Captain context: 40%, warnings available' }))
    expect(screen.getByText('Current generation · Interrupted')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Stop context continuation' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Context continuation could not be stopped. Try again.')
    await waitFor(() => expect(mocks.getSnapshot).toHaveBeenCalledTimes(2))
    expect(mocks.stopByTaskId).toHaveBeenCalledWith('captain-row'); expect(mocks.cancel).not.toHaveBeenCalled()
    expect(screen.getByRole('button', { name: 'Stop context continuation' })).not.toBeDisabled()
    mocks.stopByTaskId.mockResolvedValue({ success: false, sessionId: null })
    fireEvent.click(screen.getByRole('button', { name: 'Stop context continuation' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Refresh to check its status.')
  })
  it('does not offer continuation cancellation for completed or absent handoffs', async () => {
    mocks.getSnapshot.mockResolvedValue({ ...snapshot(), handoff: { id: 'complete', state: 'completed' } })
    const view = render(<SessionContextMeter scope={{ kind: 'commander', ownerId: 's1' }} />)
    fireEvent.click(await screen.findByRole('button', { name: 'Commander context: 40%' }))
    expect(screen.queryByRole('button', { name: 'Stop context continuation' })).toBeNull()
    view.unmount()
    mocks.getSnapshot.mockResolvedValue(snapshot())
    render(<SessionContextMeter scope={{ kind: 'commander', ownerId: 's1' }} />)
    fireEvent.click(await screen.findByRole('button', { name: 'Commander context: 40%' }))
    expect(screen.queryByRole('button', { name: 'Stop context continuation' })).toBeNull()
    expect(mocks.cancel).not.toHaveBeenCalled(); expect(mocks.stopByTaskId).not.toHaveBeenCalled()
  })
})
